const fieldVariants = cva(
  "group/field flex w-full gap-1.5",
  {
    variants: {
      orientation: {
        vertical: "flex-col *:w-full [&>.sr-only]:w-auto",
        horizontal:
          "flex-row items-center has-[>[data-slot=field-content]]:items-start *:data-[slot=field-label]:flex-auto has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
        /* Label in a fixed column so every control's left edge aligns. */
        responsive:
          "flex-col *:w-full [&>.sr-only]:w-auto @md/field-group:grid @md/field-group:grid-cols-[8.25rem_minmax(0,1fr)] @md/field-group:items-start @md/field-group:gap-x-4 @md/field-group:*:data-[slot=field-label]:pt-[calc((var(--control-h)-1lh)/2)] @md/field-group:*:not-data-[slot=field-label]:col-start-2",
      },
    },
    defaultVariants: {
      orientation: "vertical",
    },
  }
)

function Field({
  className,
  orientation = "vertical",
  ...props
}: React.ComponentProps<"div"> & VariantProps<typeof fieldVariants>) {
  return (
    <div
      role="group"
      data-slot="field"
      data-orientation={orientation}
      className={cn(fieldVariants({ orientation }), className)}
      {...props}
    />
  )
}

